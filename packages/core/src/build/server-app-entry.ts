import { writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  materializedRouteModuleSource,
  type RouteInstanceSpec,
} from "../plugin/routes.ts";
import { buildEntrySource, type EntryAppContext } from "./entry-template.ts";
import { ensureDir, toPosixPath } from "./shared.ts";

interface MaterializeServerAppEntryOptions {
  apps: EntryAppContext[];
  headerComment: string;
  instances: RouteInstanceSpec[];
  outDir: string;
  serverEntry: string;
}

export async function materializeServerAppEntry(
  options: MaterializeServerAppEntryOptions
): Promise<string> {
  ensureDir(options.outDir);
  const apps = await Promise.all(
    options.apps.map(async (app, index): Promise<EntryAppContext> => {
      const instance = options.instances[index];
      if (!instance) {
        throw new Error(`[furin] Missing route instance for server app ${index}.`);
      }
      const routePath = join(options.outDir, `_furin-routes-${index}.ts`);
      writeFileSync(routePath, await materializedRouteModuleSource(instance));
      return { ...app, nativeRoutes: toPosixPath(routePath) };
    })
  );
  const entryPath = join(options.outDir, "_furin-app.ts");
  writeFileSync(
    entryPath,
    buildEntrySource({
      apps,
      headerComment: options.headerComment,
      mode: "app",
      serverEntry: options.serverEntry,
    })
  );
  return entryPath;
}

export function serverBootSource(appEntry: string): string {
  return `// Auto-generated by furin build - do not edit
import app, { port, startServer } from ${JSON.stringify(toPosixPath(appEntry))};

if (typeof startServer === "function") {
  await startServer();
} else if (app && typeof app.listen === "function" && !app.server) {
  const serverPort = process.env.PORT === undefined
    ? typeof port === "number" ? port : 3000
    : Number(process.env.PORT);
  app.listen(serverPort);
  console.log(\`[furin] Server running at http://localhost:\${app.server?.port}\`);
}
`;
}
